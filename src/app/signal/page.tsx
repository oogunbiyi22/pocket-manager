function scoreFit(song: SongCatalogItem, playlist: typeof PLAYLIST_POOL[0]): number {
  let score = 50;
  const songGenre = (song.genre ?? "").toLowerCase();
  const songMood = (song.mood ?? "").toLowerCase();
  const plGenre = playlist.primaryGenre.toLowerCase();
  const plMood = playlist.mood.toLowerCase();

  // Genre matching
  if (songGenre && plGenre.includes(songGenre)) score += 30;
  else if (songGenre && (plGenre.includes("r&b") && songGenre.includes("r&b"))) score += 20;
  else if (songGenre && plGenre.split(/[/,&\s]/).some((g: string) => g.trim() && songGenre.includes(g.trim()))) score += 15;

  // Mood matching
  const moodWords = plMood.split(/[,\s]+/).filter(Boolean);
  const matches = moodWords.filter((w: string) => songMood.includes(w)).length;
  score += Math.min(matches * 8, 20);

  // Cap 0-99
  return Math.min(99, Math.max(30, score));
}

function loadState(): SignalState {
  if (typeof window === "undefined") return { pitches: [], lastPitchRun: null };
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) return JSON.parse(raw) as SignalState;
  } catch { /* noop */ }
  return { pitches: [], lastPitchRun: null };
}

function saveState(state: SignalState) {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
}

